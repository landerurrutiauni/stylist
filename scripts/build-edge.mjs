// Bundles the API's own code for Supabase Edge Functions (Deno) into one ES
// module. npm dependencies stay as `npm:` imports at the versions in
// package-lock.json, which Deno resolves when the function is deployed.
//   node scripts/build-edge.mjs  ->  supabase/functions/folia-analyze/index.js
import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';

const lock = JSON.parse(await readFile('package-lock.json', 'utf8'));
const version = (name) => lock.packages[`node_modules/${name}`].version;
const NPM = { zod: `npm:zod@${version('zod')}`, '@anthropic-ai/sdk': `npm:@anthropic-ai/sdk@${version('@anthropic-ai/sdk')}` };

const npmImports = {
  name: 'npm-imports',
  setup(context) {
    context.onResolve({ filter: /^(zod|@anthropic-ai\/sdk)$/ }, (args) => ({ path: NPM[args.path], external: true }));
  },
};

const outfile = 'supabase/functions/folia-analyze/index.js';
const result = await build({
  entryPoints: ['server/supabase/index.ts'],
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  plugins: [npmImports],
  banner: { js: '// Generated by scripts/build-edge.mjs from server/. Do not edit.' },
  metafile: true,
  logLevel: 'warning',
});

const bytes = Object.values(result.metafile.outputs).reduce((sum, output) => sum + output.bytes, 0);
console.log(`Edge bundle: ${outfile} (${(bytes / 1024).toFixed(0)} kB) with ${Object.values(NPM).join(', ')}`);
