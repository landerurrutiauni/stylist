import type { Aesthetic, Density, Expression, Texture, Tool } from '../schema/answers.ts';
import type { Difficulty, LengthCategory } from '../labels.ts';

/**
 * Parameters for the head-sheet drawing of a cut (see src/figures).
 * They describe the silhouette, not a person: the drawing is a stylist's
 * diagram of the shape, never a picture of the user.
 */
export interface FigureSpec {
  /** Hair height above the skull at the crown: 0 (shaved) to 1 (large afro). */
  top: number;
  /** How the sides sit against the head. */
  sides: 'skin' | 'short' | 'close' | 'full' | 'wide';
  /** Where the longest hair ends. */
  length: 'crown' | 'ear' | 'cheek' | 'jaw' | 'chin' | 'nape' | 'shoulder' | 'collarbone' | 'chest' | 'back';
  fringe: 'none' | 'micro' | 'blunt' | 'curtain' | 'side' | 'textured' | 'up';
  part: 'none' | 'center' | 'side';
  texture: 'straight' | 'wavy' | 'curly' | 'coily' | 'braids';
  layers: 'none' | 'light' | 'heavy';
  /** Nape longer than the sides (mullet, wolf cut). */
  napeLonger?: boolean;
  /** Hair combed away from the face. */
  swept?: 'back' | 'side';
  /** One side longer than the other. */
  asymmetric?: boolean;
  /** Long hair gathered into a bun at the crown. */
  bun?: boolean;
}

export interface CatalogStyle {
  id: string;
  name: string;
  length: LengthCategory;
  /** Style codes the cut belongs to. Never inferred from the user. */
  expressions: Exclude<Expression, 'mixed' | 'all'>[];
  aesthetics: Aesthetic[];
  /** Textures the cut is designed for. */
  textures: Exclude<Texture, 'unsure'>[];
  densities: Exclude<Density, 'unsure'>[];
  /** Typical styling time per day, in minutes. */
  minutes: number;
  /** Weeks between trims to keep the shape. */
  cadence: [number, number];
  difficulty: Difficulty;
  tools: Exclude<Tool, 'none'>[];
  summary: string;
  /** What the cut looks like, in plain English, for the image model that draws it on the person's photo. */
  look: string;
  /** What to ask for at the salon or barbershop, in trade terms. */
  barber: string;
  /** The trade-off that comes with the cut, before any personal adjustment. */
  tradeoff: string;
  figure: FigureSpec;
}

